"""The game's pixel shaders that draw the ground, by hash: the terrain's (they sample `sampler_heightmap`) and the ground
patches' (only generic samplers, `sampler_Texture<n>`, and `sampler_OcclusionTexture`, the level's occlusion map),
among those that take the outdoor light. Ours: hashes only, no shader code.

    python -I tools/ground_shaders.py --game bf/assets --out bf/third_party/native-x-renderer/src/bf_ground.inc

D241: the ground's relief (tyre ruts, footprints, ripples in its normal maps) is lit by a lower sun than the sky's when
the sky's stands high; see NativeXRenderer's ApplyOutdoorLight. Read from the shaders' constant tables as
tools/light_constants.py reads them (24 Nov 2026: 240 terrain shaders and 90 ground patches' of 791 that take the
outdoor light; no shader samples the occlusion map with named samplers, so props, whose samplers are named, are not
taken).
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fbrb_extract  # noqa: E402
import light_constants  # noqa: E402

GENERIC = re.compile(r'^sampler_(Texture\d*|OcclusionTexture)$')


def ground(table):
    if 'outdoorLightDir' not in table:
        return None
    samplers = [k for k, v in table.items() if v[0] == 3 and k != 'outdoorLightShadowmapTexture']
    if 'sampler_heightmap' in samplers:
        return 'terrain'
    if 'sampler_OcclusionTexture' in samplers and all(GENERIC.match(s) for s in samplers):
        return 'patch'
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', required=True, help='the game folder (its dist folder inside)')
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    found = {}
    seen = set()
    for root, _, files in os.walk(os.path.join(a.game, 'dist')):
        for name in sorted(files):
            if not name.endswith('.fbrb'):
                continue
            try:
                _, entries, data = fbrb_extract.read(os.path.join(root, name))
            except (ValueError, OSError, EOFError) as e:
                print('not read:', name, e, file=sys.stderr)
                continue
            for e in entries:
                blob = data[e['offset']:e['offset'] + e['size']]
                for at, h in light_constants.pixel_shaders(blob):
                    if h in seen:
                        continue
                    seen.add(h)
                    table = light_constants.constant_table(blob, at, True)
                    kind = ground(table) if table else None
                    if kind:
                        found[h] = kind
    with open(a.out, 'w', newline='\n') as f:
        f.write('// Generated by tools/ground_shaders.py from the game\'s shader constant tables: do not edit.\n')
        f.write('// The pixel shaders that draw the ground (D241): {hash, 1 the terrain\'s or 2 a ground patch\'s}. Sorted '
                'by hash.\n')
        for h in sorted(found):
            f.write('{0x%016XULL, %d},  // %s\n' % (h, 1 if found[h] == 'terrain' else 2, found[h]))
    kinds = list(found.values())
    print('%d ground shaders (%d terrain, %d patches) of %d pixel shaders' %
          (len(found), kinds.count('terrain'), kinds.count('patch'), len(seen)))


if __name__ == '__main__':
    main()
