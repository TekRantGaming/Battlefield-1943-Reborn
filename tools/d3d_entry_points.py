"""The Direct3D library's entry points: functions in the XDK library range (0x82160000 to 0x82181000, see
docs/renderer-feasibility.md) that code outside the range calls, from the generated code.

    python -I tools/d3d_entry_points.py [--generated bf/generated/default] [--out bf/native-renderer/d3d_entry_points.txt]
                                        [--hooks bf/src/native_hook_list.inc]

Writes one line per entry point: address, call sites outside the library, calling functions; and the hook list the
game's native renderer hooks include (bf/src/native_hooks.cpp), one BF_NATIVE_HOOK(address) per entry point.
"""
import argparse
import collections
import glob
import os
import re

LOW, HIGH = 0x82160000, 0x82181000
OWN_HOOKS = {0x82180220}  # the shader constants begin call
# The library's own functions that build draw packets (tools/pm4_scan.py: DRAW_INDX in 4, DRAW_INDX_2 in 7), hooked
# too, called from the engine or not: together they account for every draw in the frame log.
DRAW_BUILDERS = {0x8216B718, 0x8217F388, 0x8217F868, 0x8217FC58, 0x8216AB88, 0x8216D448, 0x8216DCC0, 0x821765B8,
                 0x82176710, 0x8217ABD0, 0x8217E0D0}
# The command buffer segment kick (the one INDIRECT_BUFFER site, sub_82165058) and its four callers: each kick
# seems to come with a block of 24 small draws (16x16 scissor, no pixel shader) that no draw builder makes.
SEGMENT_KICKS = {0x82165058, 0x821656B0, 0x82165788, 0x8217C468, 0x8217CBA0}

ap = argparse.ArgumentParser()
ap.add_argument('--generated', default='bf/generated/default')
ap.add_argument('--out', default='bf/native-renderer/d3d_entry_points.txt')
ap.add_argument('--hooks', default='bf/src/native_hook_list.inc')
a = ap.parse_args()

define = re.compile(r'^(?:DEFINE_REX_FUNC|PPC_FUNC_IMPL)\((?:__imp__)?sub_([0-9A-F]{8})\)')
call = re.compile(r'\bsub_([0-9A-F]{8})\(ctx, base\);')
sites = collections.Counter()
callers = collections.defaultdict(set)
defined = set()
for path in sorted(glob.glob(os.path.join(a.generated, '*.cpp'))):
    current = None
    for line in open(path, encoding='utf-8', errors='replace'):
        m = define.match(line)
        if m:
            current = int(m.group(1), 16)
            defined.add(current)
            continue
        if current is None or LOW <= current < HIGH:
            continue
        for c in call.finditer(line):
            target = int(c.group(1), 16)
            if LOW <= target < HIGH:
                sites[target] += 1
                callers[target].add(current)
entries = sorted(t for t in sites if t in defined)
with open(a.out, 'w', encoding='ascii', newline='\n') as f:
    f.write('# Direct3D library entry points called from outside it (tools/d3d_entry_points.py): address, call '
            'sites, calling functions\n')
    for t in entries:
        f.write('%08X %d %d\n' % (t, sites[t], len(callers[t])))
with open(a.hooks, 'w', encoding='ascii', newline='\n') as f:
    f.write('// Generated by tools/d3d_entry_points.py: the Direct3D library entry points the engine calls.\n')
    for t in sorted(set(entries) | DRAW_BUILDERS | SEGMENT_KICKS):
        # Entry points with a hook of their own in native_hooks.cpp.
        f.write('%s(%08X)\n' % ('BF_NATIVE_HOOK_OWN' if t in OWN_HOOKS else 'BF_NATIVE_HOOK', t))
print('%d entry points, %d call sites, %d calling functions' % (
    len(entries), sum(sites[t] for t in entries), len(set().union(*(callers[t] for t in entries)))))
